// The real Contracts-owned Command, binding implementation, product resolver,
// Service, session boundary and HTTP Handler run together. All authority, clock,
// Integrity, applicability and persistence collaborators below remain explicit
// synthetic doubles; no real issuance configuration is enabled by this test.
